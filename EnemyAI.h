#ifndef ENEMY_AI_H
#define ENEMY_AI_H

#include <DirectXMath.h>

//==============================================================================
// AI更新処理（追跡 + 巡回）
//
// 機能説明
// ・プレイヤーが視野内 → 追跡モード
// ・プレイヤーが視野外 → 巡回モード（目的地へ移動）
// ・目的地に到達で新しい目的地をランダム設定
//
// 引数
// ・ioPosition          : エネミーの現在位置（入出力）
// ・ioVelocity          : エネミーの現在速度（入出力・移動量）
// ・ioFront             : エネミーの現在向き（入出力・回転）
// ・ioDestination       : 現在目的地（入出力・到達で自動更新）
// ・ioWasChasing        : 前フレームの追跡フラグ（入出力）
// ・ioLastSeenPos       : 最後にプレイヤーを視認した位置（入出力）
// ・ioInvestigateTimer  : 索敵残り時間（入出力・>0 で Investigate 状態）
// ・dt                  : 経過時間（秒）
// ・chaseSpeed          : 追跡時の移動速度（メートル/秒）
// ・patrolSpeed         : 巡回時の移動速度（メートル/秒）
// ・sightDistance       : 視野距離（メートル）
//==============================================================================
void EnemyAI_Update(
    DirectX::XMFLOAT3* ioPosition,
    DirectX::XMFLOAT3* ioVelocity,
    DirectX::XMFLOAT3* ioFront,
    DirectX::XMFLOAT3* ioDestination,
    bool*              ioWasChasing,
    DirectX::XMFLOAT3* ioLastSeenPos,
    float*             ioInvestigateTimer,
    float              dt,
    float              chaseSpeed,
    float              patrolSpeed,
    float              sightDistance);

//==============================================================================
// 回転速度設定
//
// 機能
// ・向き変更時の回転速度を変更する（全エネミー共通）
//
// 引数
// ・degreesPerSecond : 回転速度（度/秒）
//==============================================================================
void EnemyAI_SetRotationSpeed(float degreesPerSecond);

//==============================================================================
// 到達判定距離設定
//
// 機能
// ・目的地に「到達した」と判定する距離を変更する（全エネミー共通）
//
// 引数
// ・distance : 到達判定距離（メートル）
//==============================================================================
void EnemyAI_SetArrivalDistance(float distance);

//==============================================================================
// 視野距離倍率設定
//
// 機能
// ・EnemyAI_Update に渡される視野距離にこの倍率を掛ける（全エネミー共通）
// ・ブロックステージのミッションで、広いステージでも敵が反応するように上げる
// ・既定値 1.0（デフォルトのダンジョン・サバイバルは 1.0 のまま）
//==============================================================================
void EnemyAI_SetSightMultiplier(float multiplier);
float EnemyAI_GetSightMultiplier();

//==============================================================================
// 警報の更新（毎フレーム1回呼ぶ）
//
// 機能
// ・どれか1体がプレイヤーを視認すると「警報」が出て、18m 以内で巡回中の仲間が
//   そのときのプレイヤー位置へ急行する。警報は 1 秒で失効する
//==============================================================================
void EnemyAI_UpdateAlert(float dt);

#endif // ENEMY_AI_H
